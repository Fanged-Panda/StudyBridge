/**
 * Fill the gaps left by the first pass of build-core-1k.mjs.
 *
 * 1. Retries the Dictionary API (slowly) for words that failed.
 * 2. Falls back to DataMuse definitions for anything still missing.
 * 3. Rewrites src/modules/vocabulary/core1k.js from the cache.
 */
import { readFile, writeFile } from 'node:fs/promises';

const CACHE_PATH = '/tmp/studybridge-core1k-cache.json';
const DICTIONARY_URL = 'https://api.dictionaryapi.dev/api/v2/entries/en';
const DATAMUSE_URL = 'https://api.datamuse.com/words';

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const POS = {
  n: 'noun',
  v: 'verb',
  adj: 'adjective',
  adv: 'adverb',
  u: 'noun',
  prop: 'noun',
};

async function fetchJson(url) {
  try {
    const response = await fetch(url);
    if (!response.ok) return null;
    return await response.json();
  } catch {
    return null;
  }
}

function firstSentence(text) {
  const value = String(text || '').trim();
  if (!value) return null;
  const sentence = value.split(/(?<=[.!?])\s+/)[0];
  return sentence.length > 160 ? `${sentence.slice(0, 157).trim()}…` : sentence;
}

function fromDictionary(word, payload) {
  if (!Array.isArray(payload) || !payload.length) return null;

  const phonetic =
    payload.find((entry) => entry.phonetic)?.phonetic ||
    payload.flatMap((entry) => entry.phonetics || []).find((item) => item.text)?.text ||
    null;

  const meanings = payload.flatMap((entry) => entry.meanings || []);
  const meaning = meanings.find((entry) => (entry.definitions || []).some((def) => def.definition));
  if (!meaning) return null;

  const definition = meaning.definitions.find((item) => item.definition)?.definition?.trim();
  if (!definition) return null;

  const example =
    meanings
      .flatMap((entry) => entry.definitions || [])
      .map((item) => firstSentence(item.example))
      .find(Boolean) || null;

  const synonyms = [
    ...new Set(
      meanings
        .flatMap((entry) => entry.definitions || [])
        .flatMap((item) => item.synonyms || [])
        .map((item) => String(item).toLowerCase().trim())
        .filter((item) => item && item !== word && item.length < 20 && /^[a-z' -]+$/.test(item)),
    ),
  ].slice(0, 3);

  return {
    word,
    phonetic,
    partOfSpeech: meaning.partOfSpeech || null,
    definition: definition.length > 220 ? `${definition.slice(0, 217).trim()}…` : definition,
    example,
    synonyms,
  };
}

async function fromDatamuse(word) {
  const payload = await fetchJson(`${DATAMUSE_URL}?sp=${encodeURIComponent(word)}&md=dp&max=1`);
  const entry = Array.isArray(payload) ? payload.find((item) => item.word === word) || payload[0] : null;
  const defs = Array.isArray(entry?.defs) ? entry.defs : [];
  if (!defs.length) return null;

  const [tag, ...rest] = String(defs[0]).split('\t');
  const definition = rest.join(' ').trim();
  if (!definition) return null;

  return {
    word,
    phonetic: null,
    partOfSpeech: POS[tag] || 'noun',
    definition: definition.length > 220 ? `${definition.slice(0, 217).trim()}…` : definition,
    example: null,
    synonyms: [],
  };
}

const cache = JSON.parse(await readFile(CACHE_PATH, 'utf8'));
const missing = Object.keys(cache).filter((word) => !cache[word]);
console.log(`Missing ${missing.length} definitions. Retrying the dictionary API…`);

let recovered = 0;
for (let index = 0; index < missing.length; index += 1) {
  const word = missing[index];
  const result = fromDictionary(word, await fetchJson(`${DICTIONARY_URL}/${encodeURIComponent(word)}`));
  if (result) {
    cache[word] = result;
    recovered += 1;
  }
  if ((index + 1) % 100 === 0) {
    console.log(`  ${index + 1}/${missing.length} (${recovered} recovered)`);
    await writeFile(CACHE_PATH, JSON.stringify(cache), 'utf8');
  }
  await sleep(60);
}

console.log(`Recovered ${recovered}. Filling ${missing.length - recovered} from DataMuse…`);
let fallback = 0;
for (const word of missing.filter((entry) => !cache[entry])) {
  const result = await fromDatamuse(word);
  if (result) {
    cache[word] = result;
    fallback += 1;
  }
  await sleep(40);
}
console.log(`DataMuse filled ${fallback}.`);

await writeFile(CACHE_PATH, JSON.stringify(cache), 'utf8');

const order = Object.keys(cache);
const entries = order.map((word) => cache[word]).filter(Boolean);
const line = (entry) =>
  `  { word: ${JSON.stringify(entry.word)}, phonetic: ${JSON.stringify(entry.phonetic)}, partOfSpeech: ${JSON.stringify(
    entry.partOfSpeech,
  )}, definition: ${JSON.stringify(entry.definition)}, example: ${JSON.stringify(
    entry.example,
  )}, synonyms: ${JSON.stringify(entry.synonyms)} },`;

const file = `/**
 * English 1K: the ${entries.length} most frequently used English words with short
 * definitions. Generated by scripts/build-core-1k.mjs — regenerate instead of
 * editing by hand.
 */
export const CORE_1K = [
${entries.map(line).join('\n')}
];
`;

await writeFile(new URL('../src/modules/vocabulary/core1k.js', import.meta.url), file, 'utf8');
console.log(`Wrote ${entries.length} words (${order.length - entries.length} still missing).`);
