/**
 * Clean up senses that are useless on a flashcard (acronyms, obsolete spellings,
 * "alternative form of…"). Re-fetches only the affected words, prefers the
 * everyday part of speech, then rewrites core1k.js.
 */
import { readFile, writeFile } from 'node:fs/promises';

const CACHE_PATH = '/tmp/studybridge-core1k-cache.json';
const DICTIONARY_URL = 'https://api.dictionaryapi.dev/api/v2/entries/en';

const BAD = /^(initialism|acronym|abbreviation|alternative form|alternative spelling|misspelling|obsolete|archaic|plural of|past of|present participle of|eye dialect|nonstandard spelling|informal spelling)\b/i;
const POS_ORDER = ['article', 'preposition', 'conjunction', 'pronoun', 'determiner', 'verb', 'noun', 'adjective', 'adverb'];

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function fetchJson(url) {
  try {
    const response = await fetch(url);
    if (!response.ok) return null;
    return await response.json();
  } catch {
    return null;
  }
}

function choose(word, payload) {
  if (!Array.isArray(payload) || !payload.length) return null;

  const meanings = payload.flatMap((entry) => entry.meanings || []);
  const usable = meanings
    .map((meaning) => ({
      partOfSpeech: meaning.partOfSpeech || null,
      definitions: (meaning.definitions || []).filter(
        (item) => item.definition && !BAD.test(item.definition.trim()),
      ),
    }))
    .filter((meaning) => meaning.definitions.length);

  if (!usable.length) return null;

  const rank = (partOfSpeech) => {
    const index = POS_ORDER.indexOf(String(partOfSpeech || '').toLowerCase());
    return index === -1 ? POS_ORDER.length : index;
  };
  usable.sort((a, b) => rank(a.partOfSpeech) - rank(b.partOfSpeech));

  const meaning = usable[0];
  const definition = meaning.definitions[0].definition.trim();
  const phonetic =
    payload.find((entry) => entry.phonetic)?.phonetic ||
    payload.flatMap((entry) => entry.phonetics || []).find((item) => item.text)?.text ||
    null;

  const example =
    meanings
      .flatMap((entry) => entry.definitions || [])
      .map((item) => String(item.example || '').trim())
      .filter(Boolean)
      .map((sentence) => (sentence.length > 160 ? `${sentence.slice(0, 157).trim()}…` : sentence))[0] || null;

  const synonyms = [
    ...new Set(
      meanings
        .flatMap((entry) => entry.definitions || [])
        .flatMap((item) => item.synonyms || [])
        .map((item) => String(item).toLowerCase().trim())
        .filter((item) => item && item !== word && item.length < 20 && /^[a-z' -]+$/.test(item)),
    ),
  ].slice(0, 3);

  return {
    word,
    phonetic,
    partOfSpeech: meaning.partOfSpeech,
    definition: definition.length > 220 ? `${definition.slice(0, 217).trim()}…` : definition,
    example,
    synonyms,
  };
}

const cache = JSON.parse(await readFile(CACHE_PATH, 'utf8'));
const suspicious = Object.keys(cache).filter((word) => {
  const entry = cache[word];
  if (!entry) return false;
  return BAD.test(String(entry.definition || ''));
});

console.log(`${suspicious.length} entries have an unusable sense. Refetching…`);
let fixed = 0;
for (const word of suspicious) {
  const replacement = choose(word, await fetchJson(`${DICTIONARY_URL}/${encodeURIComponent(word)}`));
  if (replacement) {
    cache[word] = replacement;
    fixed += 1;
  } else {
    console.log(`  no clean sense for "${word}" — dropping it`);
    cache[word] = null;
  }
  await sleep(80);
}
console.log(`Fixed ${fixed}/${suspicious.length}.`);

await writeFile(CACHE_PATH, JSON.stringify(cache), 'utf8');

const entries = Object.keys(cache)
  .map((word) => cache[word])
  .filter(Boolean);
const line = (entry) =>
  `  { word: ${JSON.stringify(entry.word)}, phonetic: ${JSON.stringify(entry.phonetic)}, partOfSpeech: ${JSON.stringify(
    entry.partOfSpeech,
  )}, definition: ${JSON.stringify(entry.definition)}, example: ${JSON.stringify(
    entry.example,
  )}, synonyms: ${JSON.stringify(entry.synonyms)} },`;

const file = `/**
 * English 1K: the ${entries.length} most frequently used English words with short
 * definitions. Generated by scripts/build-core-1k.mjs and scripts/fill-core-1k.mjs
 * — regenerate instead of editing by hand.
 */
export const CORE_1K = [
${entries.map(line).join('\n')}
];
`;

await writeFile(new URL('../src/modules/vocabulary/core1k.js', import.meta.url), file, 'utf8');
console.log(`Wrote ${entries.length} words.`);
